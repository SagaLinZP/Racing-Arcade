type RawSession = {
  id: string
  stageId: string
  type: SessionType
  name_zh: string
  name_en: string
  startsAt: string
  endsAt: string
  durationMinutes?: number
  raceDuration?: number
  raceDurationType?: 'time' | 'laps'
  gameConfig?: SessionGameConfig
  splits: Split[]
}

function migrateStage(rawSessions: RawSession[]): {
  sessions: Session[]
  gameConfig?: SessionGameConfig
  splits: Split[]
} {
  if (rawSessions.length === 0) {
    return { sessions: [], splits: [] }
  }

  const race = rawSessions.find(s => s.type === 'race') ?? rawSessions[rawSessions.length - 1]
  const raceSessionId = `${race.id}_gs`

  const sessions: Session[] = rawSessions.map(s => ({
    id: `${s.id}_gs`,
    type: s.type,
    name_zh: s.name_zh,
    name_en: s.name_en,
    durationMinutes: s.durationMinutes,
    raceDuration: s.raceDuration,
    raceDurationType: s.raceDurationType,
  }))

  const splits: Split[] = race.splits.map(sp => {
    const { sessionId: _legacy, ...rest } = sp as Split & { sessionId?: string }
    void _legacy
    return {
      ...rest,
      results: rest.results?.map(r => ({ ...r, sessionId: r.sessionId ?? raceSessionId })),
    }
  })

  return {
    sessions,
    gameConfig: race.gameConfig,
    splits,
  }
}

function migrateCompetitions(raw: Record<string, unknown>[]): Competition[] {
  return raw.map(comp => {
    const c = comp as Record<string, unknown>
    return {
      ...(c as object),
      rounds: (c.rounds as Record<string, unknown>[]).map(round => {
        const r = round as Record<string, unknown>
        return {
          ...(r as object),
          stages: (r.stages as Record<string, unknown>[]).map(stage => {
            const st = stage as Record<string, unknown>
            const migrated = migrateStage(st.sessions as unknown as RawSession[])
            const stageFields = { ...st }
            delete stageFields.sessions
            return {
              ...stageFields,
              gameConfig: migrated.gameConfig,
              sessions: migrated.sessions,
              splits: migrated.splits,
            }
          }),
        }
      }),
    } as Competition
  })
}

export const competitions: Competition[] = migrateCompetitions(_rawCompetitions)
